// Browser regression: install Playwright separately or set PLAYWRIGHT_MODULE and CHROMIUM_EXECUTABLE.
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import vue from '@vitejs/plugin-vue'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ root: process.cwd(), configFile: false, plugins: [vue()], server: { host: '127.0.0.1', port: 0 }, logLevel: 'error' })
await server.listen()
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'] })
const page = await browser.newPage({ viewport: { width: 1100, height: 760 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  const url = `http://127.0.0.1:${server.httpServer.address().port}/scripts/ui-fixture/sticker-panel.html`
  await page.goto(url)
  await page.waitForFunction(() => !!window.__stickerQA)
  const menu = page.getByRole('menu')
  await page.locator('.sp-fav').click({ button: 'right' })
  assert.equal(await menu.getByText('收藏栏不可删除').count(), 1)
  assert.equal(await menu.getByRole('menuitem', { name: /删除|移出/ }).count(), 0)
  await page.locator('.sp-fav').click()
  await page.locator('.cell').first().click({ button: 'right' })
  assert.equal(await menu.getByRole('menuitem', { name: '删除这张收藏' }).count(), 1)
  assert.match(await page.evaluate(() => document.activeElement.textContent), /置顶/)
  await page.keyboard.press('ArrowDown')
  assert.match(await page.evaluate(() => document.activeElement.textContent), /删除/)
  await menu.getByRole('menuitem', { name: '删除这张收藏' }).click()
  assert.equal(await page.locator('.cell').count(), 1)
  assert.deepEqual(await page.evaluate(() => window.__stickerQA.calls.filter(x => x[0] === 'removeFavorite').map(x => x[1])), [101])
  await page.locator('.sp-pack-list .sp-pack').last().click({ button: 'right' })
  const bounds = await menu.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 1100 && bounds.y + bounds.height <= 760)
  await menu.getByRole('menuitem', { name: '移到顶部' }).click()
  assert.deepEqual(await page.locator('.sp-pack-list .sp-pack-name').allTextContents(), ['其他合集', '我创建的'])
  await page.reload()
  assert.deepEqual(await page.locator('.sp-pack-list .sp-pack-name').allTextContents(), ['其他合集', '我创建的'])
  await page.getByRole('button', { name: /其他合集/ }).click()
  assert.equal(await page.getByRole('button', { name: '移出合集' }).count(), 1)
  await page.locator('.cell').first().click({ button: 'right' })
  assert.equal(await menu.getByRole('menuitem', { name: /删除|重命名/ }).count(), 0)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /我创建的/ }).click()
  assert.equal(await page.getByRole('button', { name: '删除合集', exact: true }).count(), 1)
  await page.locator('.cell').first().click({ button: 'right' })
  assert.equal(await menu.getByRole('menuitem', { name: '从合集中删除' }).count(), 1)
  if (process.env.UI_QA_SCREENSHOTS) await page.screenshot({ path: process.env.UI_QA_SCREENSHOTS + '/sticker-panel-dark.png' })
  await menu.getByRole('menuitem', { name: '从合集中删除' }).click()
  assert.deepEqual(await page.evaluate(() => window.__stickerQA.calls.filter(x => x[0] === 'removeSticker').map(x => x.slice(1))), [[1, 11]])
  await page.setViewportSize({ width: 420, height: 760 })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })
  await page.getByRole('button', { name: '管理当前表情包' }).click()
  assert.equal(await menu.getByRole('menuitem', { name: '永久删除合集' }).count(), 1)
  const mobile = await menu.boundingBox()
  assert.ok(mobile.x >= 0 && mobile.x + mobile.width <= 420 && mobile.y + mobile.height <= 760)
  if (process.env.UI_QA_SCREENSHOTS) await page.screenshot({ path: process.env.UI_QA_SCREENSHOTS + '/sticker-panel-mobile.png' })
  assert.deepEqual(errors, [])
  console.log('PASS: actual sticker menus, deletion and permissions, account-local ordering, viewport bounds, dark and mobile light layouts')
} finally { await browser.close(); await server.close() }
